    public void workWithDatabase() {

        DefaultTableModel model = (DefaultTableModel) table2.getModel();
        int selectedRowIndex = table2.getSelectedRow();

        if (selectedRowIndex == -1) {
            JOptionPane.showMessageDialog(this, "Selecione um produto.");
            return;
        }

        try {
            String itemId = model.getValueAt(selectedRowIndex, 0).toString();
            String itemName = model.getValueAt(selectedRowIndex, 1).toString();
            int quantity = Integer.parseInt(
                    model.getValueAt(selectedRowIndex, 2).toString());
            String price = model.getValueAt(selectedRowIndex, 3).toString();
            String totalPrice = model.getValueAt(selectedRowIndex, 4).toString();

            if (quantity <= 0) {
                JOptionPane.showMessageDialog(this, "Quantidade inválida.");
                return;
            }

            String selectQuery = "SELECT quantity FROM inventory WHERE item_id = ? FOR UPDATE";

            String updateQuery = "UPDATE inventory SET quantity = ? WHERE item_id = ?";

            String insertQuery = "INSERT INTO bill(item_id, item_name, quantity, price, totprice) "
                    + "VALUES (?, ?, ?, ?, ?)";

            String deleteQuery = "DELETE FROM cart WHERE item_id = ?";

            try (Connection con = DatabaseConnection.getConnection()) {

                con.setAutoCommit(false);

                try {
                    int currentQuantity;

                    // Consulta e bloqueia o registro do estoque
                    try (PreparedStatement selectStmt = con.prepareStatement(selectQuery)) {

                        selectStmt.setString(1, itemId);

                        try (ResultSet rs = selectStmt.executeQuery()) {

                            if (!rs.next()) {
                                throw new SQLException(
                                        "Produto não encontrado no estoque.");
                            }

                            currentQuantity = rs.getInt("quantity");
                        }
                    }

                    // Verifica se existe estoque suficiente
                    if (currentQuantity < quantity) {
                        throw new SQLException(
                                "Quantidade insuficiente no estoque.");
                    }

                    int newQuantity = currentQuantity - quantity;

                    // Atualiza o estoque
                    try (PreparedStatement updateStmt = con.prepareStatement(updateQuery)) {

                        updateStmt.setInt(1, newQuantity);
                        updateStmt.setString(2, itemId);

                        if (updateStmt.executeUpdate() != 1) {
                            throw new SQLException(
                                    "Falha ao atualizar o estoque.");
                        }
                    }

                    // Registra o produto na fatura
                    try (PreparedStatement insertStmt = con.prepareStatement(insertQuery)) {

                        insertStmt.setString(1, itemId);
                        insertStmt.setString(2, itemName);
                        insertStmt.setInt(3, quantity);
                        insertStmt.setString(4, price);
                        insertStmt.setString(5, totalPrice);

                        if (insertStmt.executeUpdate() != 1) {
                            throw new SQLException(
                                    "Falha ao registrar o produto na fatura.");
                        }
                    }

                    // Remove apenas o produto selecionado do carrinho
                    try (PreparedStatement deleteStmt = con.prepareStatement(deleteQuery)) {

                        deleteStmt.setString(1, itemId);

                        if (deleteStmt.executeUpdate() != 1) {
                            throw new SQLException(
                                    "Falha ao remover o produto do carrinho.");
                        }
                    }

                    // Confirma todas as operações
                    con.commit();

                } catch (Exception e) {
                    try {
                        con.rollback();
                    } catch (SQLException rollbackError) {
                        e.addSuppressed(rollbackError);
                    }
                    throw e;
                }
            }

            JOptionPane.showMessageDialog(
                    this,
                    "Produto faturado com sucesso!");

            this.setVisible(false);

            bill mm = new bill();
            mm.setVisible(true);

        } catch (Exception e) {
            JOptionPane.showMessageDialog(
                    this,
                    "Erro ao faturar produto: " + e.getMessage());
        }
    }

