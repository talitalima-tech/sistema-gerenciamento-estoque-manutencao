    private void loadInventory() {

        DefaultTableModel model = (DefaultTableModel) table.getModel();

        model.setRowCount(0);

        String type = (String) filterType.getSelectedItem();
        String value = filterValue.getText().trim();

        String query = "SELECT * FROM inventory";
        String parameter = null;

        if (!"All".equals(type) && value.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this, "Enter a search value.");

            return;
        }

        switch (type) {

            case "ID":
                query += " WHERE item_id = ?";
                parameter = value;
                break;

            case "Name":
                query += " WHERE item_name LIKE ?";
                parameter = "%" + value + "%";
                break;

            case "Category":
                query += " WHERE category LIKE ?";
                parameter = "%" + value + "%";
                break;

            case "Batch":
                query += " WHERE batchno = ?";
                parameter = value;
                break;

            default:
                break;
        }

        try (
                Connection con = DatabaseConnection.getConnection();
                PreparedStatement stmt = con.prepareStatement(query)) {

            if (parameter != null) {
                stmt.setString(1, parameter);
            }

            try (ResultSet rs = stmt.executeQuery()) {

                while (rs.next()) {

                    model.addRow(new Object[] {
                            rs.getString("item_id"),
                            rs.getString("item_name"),
                            rs.getInt("quantity"),
                            rs.getDouble("price"),
                            rs.getString("mfd"),
                            rs.getString("exp"),
                            rs.getString("batchno"),
                            rs.getString("category")
                    });
                }
            }

            if (model.getRowCount() == 0) {

                JOptionPane.showMessageDialog(
                        this, "No products found.");
            }

        } catch (SQLException e) {

            model.setRowCount(0);

            JOptionPane.showMessageDialog(
                    this,
                    "Error loading inventory: " + e.getMessage(),
                    "Database error",
                    JOptionPane.ERROR_MESSAGE);
        }
    }

